"""Emit firmware/include/soc_ekf_tables.h from the 4.1 / ISS-025 results.

Sources
  results/ecm_scheduled.json  dfn.selected (SoC table, OCV choice), dfn.rest_ocv_points
  results/ekf_sigma_cv.json   selected (q_rc, r_v) and q_soc
  data/dfn/ocv_<T>C.npz       C/20 OCV curve the table was fitted with
The OCV, its slope and the tables are taken from the same Python objects the
reference EKF uses (ecm_ekf.OCV, ScheduledECM), so the C build sees the same
numbers. Values are written with 17 significant digits; the float build rounds
them once, at compile time. Never edit the generated header by hand.

Usage: python codegen/emit_ekf_tables.py
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "sim"))
from ecm_ekf import OCV, ScheduledECM  # noqa: E402

P0_SOC = 0.1 ** 2      # ecm_ekf.SoCEKF defaults
P0_RC = 1e-4


def reference_model(ecm: dict, cv: dict, dfn: Path):
    """(table, ocv, noise) exactly as sim/ekf_sigma_cv.py builds them."""
    d = ecm["dfn"]
    o = np.load(dfn / f"ocv_{int(d['temp_c'])}C.npz")
    ocv = OCV(o["soc"], o["ocv"])
    if d["selected"]["ocv"] != "c20":
        rp = d["rest_ocv_points"]
        ocv = ocv.corrected(np.asarray(rp["soc"]), np.asarray(rp["v"]))
    tab = ScheduledECM.from_dict(d["selected"]["table"])
    s = cv["selected"]
    noise = {"p0_soc": P0_SOC, "p0_rc": P0_RC, "q_soc": cv["q_soc"], "q_rc": s["q_rc"], "r_v": s["r_v"] ** 2}
    return tab, ocv, noise


def _arr(name: str, x) -> str:
    vals = ",\n    ".join(", ".join(f"R({v:.17g})" for v in x[k:k + 4]) for k in range(0, len(x), 4))
    return f"static const ekf_real_t {name}[{len(x)}] = {{\n    {vals}\n}};\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ecm", default=str(ROOT / "results" / "ecm_scheduled.json"))
    ap.add_argument("--cv", default=str(ROOT / "results" / "ekf_sigma_cv.json"))
    ap.add_argument("--dfn", default=str(ROOT / "data" / "dfn"))
    ap.add_argument("--out", default=str(ROOT / "firmware" / "include" / "soc_ekf_tables.h"))
    a = ap.parse_args()
    ecm, cv = json.load(open(a.ecm)), json.load(open(a.cv))
    tab, ocv, n = reference_model(ecm, cv, Path(a.dfn))
    for name, x in (("OCV soc", ocv.soc), ("knot soc", tab.soc)):
        if not np.all(np.diff(x) > 0):
            raise SystemExit(f"{name} grid must be strictly increasing")
    sha = {p: hashlib.sha256(Path(p).read_bytes()).hexdigest()[:16] for p in (a.ecm, a.cv)}
    h = [
        "/* soc_ekf_tables.h — GENERATED by codegen/emit_ekf_tables.py. Do not edit.",
        f" * model: {ecm['dfn']['selected']['variant']}, {ecm['dfn']['temp_c']} C, OCV {ecm['dfn']['selected']['ocv']}",
        *[f" * source {Path(p).name} sha256 {v}" for p, v in sha.items()],
        " */",
        "#ifndef SOC_EKF_TABLES_H",
        "#define SOC_EKF_TABLES_H",
        "",
        '#include "soc_ekf.h"',
        "",
        "#ifndef R",
        "#define R(x) ((ekf_real_t)(x))",
        "#endif",
        "",
        f"#define SOC_EKF_Q_AH    R({tab.q_ah:.17g})",
        f"#define SOC_EKF_P0_SOC  R({n['p0_soc']:.17g})",
        f"#define SOC_EKF_P0_RC   R({n['p0_rc']:.17g})",
        f"#define SOC_EKF_Q_SOC   R({n['q_soc']:.17g})",
        f"#define SOC_EKF_Q_RC    R({n['q_rc']:.17g})",
        f"#define SOC_EKF_R_V     R({n['r_v']:.17g})   /* (r_v [V])^2 */",
        "",
        f"#define SOC_EKF_OCV_N   {ocv.soc.size}",
        _arr("SOC_EKF_OCV_SOC", ocv.soc), _arr("SOC_EKF_OCV_V", ocv.v), _arr("SOC_EKF_OCV_DV", ocv.dv),
        f"#define SOC_EKF_KNOT_N  {tab.soc.size}",
        _arr("SOC_EKF_KNOT_SOC", tab.soc), _arr("SOC_EKF_KNOT_R0", tab.r0), _arr("SOC_EKF_KNOT_R1", tab.r1),
        _arr("SOC_EKF_KNOT_TAU1", tab.tau1), _arr("SOC_EKF_KNOT_R2", tab.r2), _arr("SOC_EKF_KNOT_TAU2", tab.tau2),
        "#endif /* SOC_EKF_TABLES_H */",
        "",
    ]
    Path(a.out).write_text("\n".join(h), encoding="utf-8", newline="\n")  # LF: the CBMC logs hash these bytes
    print("wrote", a.out)


if __name__ == "__main__":
    main()
